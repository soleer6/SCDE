import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const fx=JSON.parse(readFileSync(join(process.env.LOCALAPPDATA,'SCDE/integration/fixtures-claude-h04.local.json'),'utf8'));
const app='http://localhost:5173';
const b=await chromium.launch({channel:'msedge',headless:true});
const errors=[];
const p=await (await b.newContext({locale:'es-ES',viewport:{width:1366,height:900}})).newPage();
p.on('pageerror',e=>errors.push(e.message));
await p.goto(app+'/login');await p.locator('input[type=email]').fill(fx.teacher);await p.locator('input[type=password]').fill(fx.password);await p.locator('button[type=submit]').click();
await p.waitForURL(u=>!u.pathname.startsWith('/login'));
await p.goto(`${app}/instances/${fx.instanceId}/grade`);
await p.getByText(/^[01]\/1 problemas$/).waitFor();
assert.equal(await p.getByText(/P2 ajeno/).count(),0);
await p.getByRole('checkbox',{name:/Correct solution/}).check().catch(()=>{});
await p.getByText('1/1 problemas').waitFor();
const finish=p.getByRole('button',{name:'Marcar como corregido'});
assert.ok(await finish.isEnabled());
await p.screenshot({path:join(process.env.TEMP,'scde-pw','h04-real.png'),fullPage:true});
assert.deepEqual(errors,[]);console.log('H04 OK');await b.close();
