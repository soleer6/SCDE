import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const fx=JSON.parse(readFileSync(join(process.env.LOCALAPPDATA,'SCDE/integration/fixtures-claude-h15.local.json'),'utf8'));
const app='http://localhost:5173',base='http://127.0.0.1:8000/api/v1';
const b=await chromium.launch({channel:'msedge',headless:true});
const errors=[];
const p=await (await b.newContext({locale:'es-ES',viewport:{width:1366,height:900}})).newPage();
p.on('pageerror',e=>errors.push(e.message));
await p.goto(app+'/login');await p.locator('input[type=email]').fill(fx.manager);await p.locator('input[type=password]').fill(fx.password);await p.locator('button[type=submit]').click();
await p.waitForURL(u=>!u.pathname.startsWith('/login'));
await p.goto(`${app}/exams/${fx.examId}`);
await p.getByRole('button',{name:/^Publicar 2 notas/}).click();
await p.getByText(/siguen corregidas pero sin publicar/).waitFor();
const box=p.getByText(/siguen corregidas pero sin publicar/).locator('xpath=ancestor::*[@role="alert"]');
await box.getByText(/incidencias sin resolver/).waitFor();
assert.equal(await box.getByRole('listitem').count(),1);
await p.getByText(/Publicación parcial: 1 publicadas, 1 pendientes/).first().waitFor();
await p.getByRole('button',{name:/^Publicar 1 nota/}).waitFor();
await p.screenshot({path:join(process.env.TEMP,'scde-pw','h15-partial-real.png'),fullPage:true});
const m=await (await fetch(base+'/auth/login/',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:fx.manager,password:fx.password})})).json();
const l=await (await fetch(`${base}/exams/${fx.examId}/instances/`,{headers:{Authorization:'Bearer '+m.access_token}})).json();
const st=Object.fromEntries((Array.isArray(l)?l:l.results).map(i=>[i.id,i.status]));
assert.equal(st[fx.okInstanceId],'PUBLISHED');assert.equal(st[fx.blockedInstanceId],'GRADED');
assert.deepEqual(errors,[]);console.log('H15 OK');await b.close();
