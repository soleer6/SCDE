import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const fx=JSON.parse(readFileSync(join(process.env.LOCALAPPDATA,'SCDE/integration/fixtures-claude-h07.local.json'),'utf8'));
const app='http://localhost:5173',base='http://127.0.0.1:8000/api/v1';
const b=await chromium.launch({channel:'msedge',headless:true});
const errors=[];
const p=await (await b.newContext({locale:'es-ES',viewport:{width:1366,height:900}})).newPage();
p.on('pageerror',e=>errors.push(e.message));
await p.goto(app+'/login');await p.locator('input[type=email]').fill(fx.manager);await p.locator('input[type=password]').fill(fx.password);await p.locator('button[type=submit]').click();
await p.waitForURL(u=>!u.pathname.startsWith('/login'));
await p.goto(app+'/reviews');
await p.getByText('Solicitud sintética H07').waitFor();
await p.screenshot({path:join(process.env.TEMP,'scde-pw','h07-inbox-real.png'),fullPage:true});
const reply='Revisado por coordinación H07';
await p.getByRole('textbox').first().fill(reply);
const put=p.waitForResponse(r=>r.url().includes('/resolve/')&&r.request().method()==='PATCH');
await p.getByRole('button',{name:/^Resolver/}).click();
assert.equal((await put).status(),200);
await p.getByText('Solicitud sintética H07').waitFor({state:'detached'});
// persisted: student sees it resolved with the message
const s=await (await fetch(base+'/auth/login/',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:fx.requester,password:fx.password})})).json();
const list=await (await fetch(`${base}/instances/${fx.requesterInstanceId}/review-requests/`,{headers:{Authorization:'Bearer '+s.access_token}})).json();
const r=(Array.isArray(list)?list:list.results).find(x=>x.id===fx.requestId);
assert.ok(r.resolved&&r.resolver_message===reply);
await p.reload();await p.getByRole('heading',{name:/./}).first().waitFor();
assert.equal(await p.getByText('Solicitud sintética H07').count(),0);
assert.deepEqual(errors,[]);
console.log('H07 OK');await b.close();
