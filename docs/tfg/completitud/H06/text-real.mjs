import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const fx=JSON.parse(readFileSync(join(process.env.LOCALAPPDATA,'SCDE/integration/fixtures-claude-h04.local.json'),'utf8'));
const app='http://localhost:5173',base='http://127.0.0.1:8000/api/v1';
const b=await chromium.launch({channel:'msedge',headless:true});
const errors=[];
const p=await (await b.newContext({locale:'es-ES',viewport:{width:1366,height:900}})).newPage();
p.on('pageerror',e=>errors.push(e.message));
await p.goto(app+'/login');await p.locator('input[type=email]').fill(fx.teacher);await p.locator('input[type=password]').fill(fx.password);await p.locator('button[type=submit]').click();
await p.waitForURL(u=>!u.pathname.startsWith('/login'));
const t=await (await fetch(base+'/auth/login/',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:fx.teacher,password:fx.password})})).json();
const mine=async()=>{const l=await (await fetch(`${base}/instances/${fx.instanceId}/annotations/`,{headers:{Authorization:'Bearer '+t.access_token}})).json();return (Array.isArray(l)?l:l.results).filter(a=>a.annotation_type==='TEXT'&&a.problem_id===fx.ownProblem);};
await p.goto(`${app}/instances/${fx.instanceId}/grade`);
const box=p.getByLabel('Comentario del problema P1');
await box.waitFor();
const n0=(await mine()).length;
await box.fill('Revisa el signo en el segundo paso');
await p.getByRole('button',{name:'Guardar comentario de P1'}).click();
await p.getByText('Comentario guardado').waitFor();
let a=await mine();assert.equal(a.length,Math.max(n0,1));
assert.equal(await (await fetch(a[0].download_url)).text(),'Revisa el signo en el segundo paso');
await p.reload();
await p.waitForFunction(()=>document.querySelector('textarea[aria-label="Comentario del problema P1"]')?.value==='Revisa el signo en el segundo paso');
await p.getByLabel('Comentario del problema P1').fill('Revisa el signo (editado)');
await p.getByRole('button',{name:'Guardar comentario de P1'}).click();
await p.getByText('Comentario guardado').last().waitFor();
a=await mine();assert.equal(a.length,1);assert.equal(await (await fetch(a[0].download_url)).text(),'Revisa el signo (editado)');
await p.screenshot({path:join(process.env.TEMP,'scde-pw','h06-text-real.png'),fullPage:true});
await p.getByLabel('Comentario del problema P1').fill('');
await p.getByRole('button',{name:'Guardar comentario de P1'}).click();
await p.getByText('Comentario eliminado').waitFor();
assert.equal((await mine()).length,0);
assert.deepEqual(errors,[]);console.log('H06 texto OK');await b.close();
