/* eslint-disable react-refresh/only-export-components */
import '@testing-library/jest-dom/vitest';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { afterEach, expect, it } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import i18n from '../../../app/i18n.js';
import { ToastProvider } from '../../../ui';
import { USE_MOCK } from '../../../lib/api/client.js';
import { createAnnotation, listAnnotations, readAnnotationPayload, updateAnnotation } from '../api.js';
import ProblemNote from '../ProblemNote.jsx';
import { signIn } from './session.js';
afterEach(cleanup);
it('H48 real HTTP: two own TEXT editable, foreign read-only, drafts/reload and server authorization', async () => {
  expect(USE_MOCK).toBe(false);
  const fx = JSON.parse((await readFile(join(process.env.LOCALAPPDATA, 'SCDE/integration/fixtures-a-h48.local.json'), 'utf8')).trimStart());
  await i18n.changeLanguage('es');
  const owner = await signIn(fx, 'manager');
  expect(await listAnnotations(fx.instanceId), 'fresh fixture only; do not rerun consumed fixture').toHaveLength(0);
  const create = (payload) => createAnnotation(fx.instanceId, { annotation_type: 'TEXT', payload, problem_id: fx.problemId, page_number: 1, x: 0, y: 0 });
  const first = await create('H48 own first');
  const second = await create('H48 own second');
  await signIn(fx, 'teacher');
  const foreign = await create('H48 foreign');
  await signIn(fx, 'manager');
  const mount = (canEdit = true) => render(<ToastProvider><ProblemNote instanceId={fx.instanceId} problem={{ id: fx.problemId, name: 'P1' }} canEdit={canEdit} currentUserId={owner.user.id} /></ToastProvider>);
  let view = mount();
  await screen.findByDisplayValue('H48 own second', {}, { timeout: 15000 });
  expect(screen.getAllByRole('textbox')).toHaveLength(2);
  expect(screen.getByText('H48 foreign')).toHaveClass('gr-note__other');
  const change = (old, value) => fireEvent.change(screen.getByDisplayValue(old), { target: { value } });
  const saveFor = (value) => screen.getByDisplayValue(value).nextElementSibling;
  change('H48 own first', 'H48 first draft');
  change('H48 own second', 'H48 second saved');
  fireEvent.click(saveFor('H48 second saved'));
  await screen.findByText('Comentario guardado', {}, { timeout: 15000 });
  await screen.findByDisplayValue('H48 first draft');
  fireEvent.click(saveFor('H48 first draft'));
  await waitFor(async () => {
    const data = await listAnnotations(fx.instanceId);
    expect(await readAnnotationPayload(data.find((a) => a.id === first.id))).toBe('H48 first draft');
    expect(await readAnnotationPayload(data.find((a) => a.id === second.id))).toBe('H48 second saved');
  }, { timeout: 15000 });
  view.unmount(); view = mount();
  await screen.findByDisplayValue('H48 second saved', {}, { timeout: 15000 });
  expect(screen.getByDisplayValue('H48 first draft')).toBeInTheDocument();
  await expect(updateAnnotation(foreign.id, { payload: 'forbidden overwrite' })).rejects.toMatchObject({ status: 403 });
  // The UI still has the old author's identity; the real server must reject its write.
  await signIn(fx, 'teacher');
  change('H48 second saved', 'H48 retry draft');
  fireEvent.click(saveFor('H48 retry draft'));
  await screen.findByText('No se ha podido guardar el comentario.', {}, { timeout: 15000 });
  await screen.findByDisplayValue('H48 retry draft', {}, { timeout: 15000 });
  await signIn(fx, 'manager');
  fireEvent.click(saveFor('H48 retry draft'));
  await waitFor(async () => {
    const data = await listAnnotations(fx.instanceId);
    expect(await readAnnotationPayload(data.find((a) => a.id === second.id))).toBe('H48 retry draft');
    expect(await readAnnotationPayload(data.find((a) => a.id === foreign.id))).toBe('H48 foreign');
    expect(data).toHaveLength(3);
  }, { timeout: 15000 });
  view.unmount(); view = mount(false);
  await screen.findByText('H48 retry draft', {}, { timeout: 15000 });
  expect(screen.queryByRole('textbox')).not.toBeInTheDocument();
  await signIn(fx, 'student');
  fireEvent(window, new Event('focus'));
  await waitFor(() => expect(screen.queryByText('H48 retry draft')).not.toBeInTheDocument());
  await expect(listAnnotations(fx.instanceId)).rejects.toMatchObject({ status: 403 });
  await signIn(fx, 'manager');
  fireEvent(window, new Event('focus'));
  await screen.findByText('H48 retry draft', {}, { timeout: 15000 });
  console.log('H48 PASS: three persisted TEXT, both own updated, foreign unchanged, remount, sibling draft, real 403/retry and read authorization. No DELETE.');
});
